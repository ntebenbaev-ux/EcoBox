import 'dotenv/config';
import express from 'express';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { GoogleGenAI, ThinkingLevel } from '@google/genai';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const PORT = Number(process.env.PORT) || 3000;

interface HistoryTurn {
  sender: 'bot' | 'user';
  text: string;
}

function usesFormalYou(text: string): boolean {
  const q = text.toLowerCase();
  return /\b(вы|вам|вас|вами|ваш|ваша|ваши|подскажите|помогите|расскажите|объясните|здравствуйте)\b/.test(
    q
  );
}

function getLocalEcoBotReply(message: string, language: 'ru' | 'kk', balance: number): string {
  const q = message.toLowerCase();
  const formal = usesFormalYou(message);

  if (language === 'kk') {
    if (
      q.includes('қате') ||
      q.includes('есептелме') ||
      q.includes('адал') ||
      q.includes('бұзыл') ||
      q.includes('істемей') ||
      q.includes('техник')
    ) {
      return 'Егер материал қате таңдалса немесе ақылды контейнер қатені тіркесе, жүйе бұл туралы хабарлайды және EcoCoins есептелмейді — бұл оқушылар мен сыныптардың әділ рейтингін сақтауға көмектеседі.\nАл егер контейнерде техникалық ақау болса, мектеп әкімшісіне немесе EcoBox техникалық қолдау қызметіне жүгінуді ұсынамын.';
    }
    if (q.includes('қалай') || q.includes('пайдалан') || q.includes('нұсқау')) {
      return 'EcoBox қолдану тәртібі:\n1. Ақылды контейнер сканеріне жеке QR-кодыңды көрсет.\n2. Ашылған тиісті бөлімге қалдықты сал (пластик, шыны немесе металл).\n3. Балансыңа EcoCoins алып, операциялар тарихын бақыла.\n4. Жиналған баллдарды мектеп асханасында QR-код арқылы тәттілер мен эко-бонустарға айырбаста!';
    }
    if (q.includes('пластик') || q.includes('металл') || q.includes('шыны') || q.includes('өткіз')) {
      return 'EcoBox контейнеріне таза пластик (+15 EC), металл (+10 EC) және шыны (+20 EC) өткізуге болады. Егер материал дұрыс таңдалмаса, контейнер қатені тіркеп, балл есептемейді.';
    }
    if (q.includes('асхана') || q.includes('жұмса') || q.includes('баланс')) {
      return `Қазіргі балансың: ${balance} EcoCoins. «Асхана» бөлімінде шырын, сэндвич, тоқаш, жеміс жинағы немесе эко-шоппер таңдап, QR-код арқылы төлей аласың.`;
    }
    if (q.includes('ойын')) {
      return '«Ойындар» бөлімінде «EcoBox Сұрыптаушысы» және «Эко-әдеттер» ойындарын ойнап, жоғары нәтижелер үшін қосымша EcoCoins ұтып алуға болады!';
    }
    return `Сәлем! Мен EcoBox ресми эко-гидімін. Жоба бөлек қоқыс жинауды геймификациямен біріктіреді: пластик, шыны және металл өткізіп EcoCoins жинап, асханада жұмсай аласың. Қазіргі балансың — ${balance} EC. Нақты қай сұрақ қызықтырады?`;
  }

  if (
    q.includes('сломал') ||
    q.includes('не работает') ||
    q.includes('завис') ||
    q.includes('техн') ||
    q.includes('проблем') ||
    q.includes('сканер')
  ) {
    return formal
      ? 'Если с умным контейнером EcoBox возникла техническая неисправность (не считывается QR-код, не открывается отсек или сбой датчика), пожалуйста, обратитесь к школьному администратору или в службу техподдержки EcoBox.'
      : 'Если с умным контейнером EcoBox возникла техническая проблема (не открывается отсек или не считывается QR), обратись к школьному администратору или в техподдержку — они быстро всё проверят!';
  }

  if (q.includes('ошиб') || q.includes('не начисл') || q.includes('честн') || q.includes('обман')) {
    return formal
      ? 'Правила сортировки и честности в EcoBox строгие: если материал выбран неправильно или датчик контейнера зафиксировал ошибку, система сообщает об этом, и EcoCoins не начисляются. Так поддерживается честный рейтинг учеников и классов.'
      : 'Если материал выбран неправильно или контейнер зафиксировал ошибку, система сразу сообщает об этом, и баллы не начисляются. Это помогает сохранять честный рейтинг учеников и классов!';
  }

  if (q.includes('пользова') || q.includes('инструкц') || q.includes('как работ')) {
    return formal
      ? 'Пользоваться приложением EcoBox просто:\n1. Покажите свой персональный QR-код на сканере умного контейнера EcoBox.\n2. Сдайте отходы в открывшийся нужный отсек (пластик, стекло или металл).\n3. Получите EcoCoins на баланс и отслеживайте историю операций.\n4. Обменивайте накопленные баллы на угощения в школьной столовой по QR-коду.'
      : 'Пользоваться приложением EcoBox очень просто:\n1. Покажи свой персональный QR-код на сканере умного контейнера EcoBox.\n2. Сдай отходы в открывшийся нужный отсек (пластик, стекло или металл).\n3. Получи EcoCoins на свой баланс и следи за историей операций.\n4. Обменивай баллы на угощения в школьной столовой по QR-коду!';
  }

  if (q.includes('сдавать') || q.includes('пластик') || q.includes('металл') || q.includes('стекл') || q.includes('сортиров')) {
    return formal
      ? 'Умный контейнер EcoBox принимает три чистые фракции:\n• Пластик (+15 EC): ПЭТ-бутылки и пластиковые крышки.\n• Металл (+10 EC): алюминиевые банки.\n• Стекло (+20 EC): стеклянные бутылки и банки без крышек.\nВажно: выбирайте правильный отсек — при ошибке контейнера баллы не начисляются.'
      : 'В умный контейнер EcoBox принимаются три фракции:\n• Пластик (+15 EC): чистые ПЭТ-бутылки.\n• Металл (+10 EC): алюминиевые банки.\n• Стекло (+20 EC): чистые стеклянные бутылки без крышек.\nПомни: если выбрать неверный отсек, контейнер зафиксирует ошибку и баллы не начислятся.';
  }

  if (q.includes('потрат') || q.includes('столов') || q.includes('куп') || q.includes('бонус')) {
    return formal
      ? `Сейчас на балансе ${balance} EcoCoins. Во вкладке «Столовая» можно выбрать сок (50 EC), выпечку (40 EC), фруктовый набор (60 EC), сэндвич (70 EC) или фирменный эко-шоппер (450 EC) и получить QR-купон для кассы.`
      : `Сейчас у тебя ${balance} EcoCoins. Перейди во вкладку «Столовая», выбери сок (50 EC), булочку (40 EC), фруктовый набор (60 EC), сэндвич (70 EC) или эко-шоппер (450 EC) и нажми «Получить QR» для оплаты на кассе!`;
  }

  if (q.includes('игр') || q.includes('мини')) {
    return 'Во вкладке «Игры» есть два обучающих режима: «Сортировщик EcoBox» (30 секунд на распределение вторсырья) и викторина «Эко-привычки». За высокие результаты ты получаешь от +5 до +25 EcoCoins!';
  }

  if (q.includes('педагог') || q.includes('учител') || q.includes('школ') || q.includes('проект') || q.includes('стартап')) {
    return formal
      ? 'EcoBox — это школьный эко-тех стартап, объединяющий умный контейнер для раздельного сбора (пластик, стекло, металл) и школьный банк экобаллов EcoCoins. Ученики сдают вторсырьё по QR-коду, соревнуются в честном рейтинге классов и обменивают баллы на бонусы в школьной столовой.'
      : 'EcoBox — это школьный эко-тех стартап: умный контейнер для раздельного сбора (пластик, стекло, металл) + школьный банк экобаллов EcoCoins. Сдавай вторсырьё, соревнуйся в честном рейтинге и обменивай баллы в столовой!';
  }

  return formal
    ? `Здравствуйте! Я официальный эко-гид EcoBox. Помогу с правилами сортировки (пластик, стекло, металл), начислением EcoCoins (сейчас на балансе ${balance} EC), работой честного рейтинга и оплатой бонусов в столовой. Какой у вас вопрос?`
    : `Привет! Я официальный эко-гид EcoBox. Помогу разобраться в приложении, правилах сортировки пластика, стекла и металла, начислении EcoCoins (у тебя сейчас ${balance} EC), мини-играх и обмене баллов в столовой. О чём хочешь спросить?`;
}

async function startServer() {
  const app = express();
  app.use(express.json());

  app.post('/api/ecobot', async (req, res) => {
    const {
      message = '',
      language = 'ru',
      balance = 245,
      levelName = 'Новичок',
      rank = 5,
      history = [],
    } = req.body || {};

    const cleanMessage = String(message).trim();
    if (!cleanMessage) {
      res.status(400).json({ error: 'Empty message' });
      return;
    }

    const lang = language === 'kk' ? 'kk' : 'ru';
    const apiKey = process.env.GEMINI_API_KEY;

    if (!apiKey || apiKey === 'MY_GEMINI_API_KEY') {
      res.json({
        reply: getLocalEcoBotReply(cleanMessage, lang, Number(balance) || 245),
        source: 'local',
      });
      return;
    }

    try {
      const ai = new GoogleGenAI({
        apiKey,
        httpOptions: {
          headers: {
            'User-Agent': 'aistudio-build',
          },
        },
      });

      const baseRuInstruction = `Ты — официальный ИИ-агент и эко-гид мобильного приложения «EcoBox» (школьный эко-тех стартап: умный контейнер + школьный банк экобаллов EcoCoins).

Твоя задача — вежливо, точно и правильно отвечать на любые вопросы пользователей (школьников, педагогов и администрации), помогать им разбираться в функционале приложения, правилах сортировки мусора и начислении баллов.

КЛЮЧЕВЫЕ ПРАВИЛА И ЗНАНИЯ ДЛЯ ОТВЕТОВ:
1. Суть проекта EcoBox: Проект объединяет раздельный сбор отходов (пластик, стекло, металл) с геймификацией. За сдачу мусора ученики получают цифровую школьную валюту EcoCoins (пластик +15 EC, металл +10 EC, стекло +20 EC), которую могут тратить на полезные бонусы в школьной столовой (сок 50 EC, булочка 40 EC, фруктовый набор 60 EC, сэндвич 70 EC, фирменный эко-шоппер EcoBox 450 EC — без Wi-Fi и сторонних услуг).
2. Как пользоваться приложением:
   - Покажи свой персональный QR-код на сканере умного контейнера EcoBox.
   - Сдай отходы в открывшийся нужный отсек (пластик, стекло или металл).
   - Получи EcoCoins на свой баланс и следи за историей операций.
   - Обменивай накопленные баллы на угощения в столовой по QR-коду.
3. Дополнительные разделы: «Игры» (обучающие мини-игры «Сортировщик EcoBox» и «Эко-привычки» с наградами в EcoCoins), «Достижения» и «Рейтинг» (Топ-ученики, Топ-классы, Эко-герои).
4. Правила сортировки и честности: Если материал выбран неправильно или контейнер зафиксировал ошибку, система сообщает об этом, и баллы не начисляются. Система создаёт честный рейтинг учеников и классов.
5. Стиль общения: Будь дружелюбным, поддерживай эко-инициативы, общайся на «ты» или «вы» в зависимости от тона пользователя, отвечай чётко и по делу без лишней воды. Если вопрос касается технических проблем с контейнером, советуй обратиться к школьному администратору или в техподдержку.

Контекст текущей сессии ученицы Томирис (8 «А» класс): баланс ${balance} EcoCoins, уровень «${levelName}», место в рейтинге #${rank}. Отвечай на русском языке.`;

      const baseKkInstruction = `Сен — «EcoBox» мобильді қосымшасының ресми ЖИ-агенті және эко-гидісің (мектептегі эко-тех стартап: ақылды контейнер + EcoCoins мектеп экобалл банкі).
Оқушылардың, мұғалімдердің және әкімшіліктің кез келген сұрақтарына сыпайы, нақты және дұрыс жауап бер.
НЕГІЗГІ ЕРЕЖЕЛЕР:
1. EcoBox мәні: қалдықтарды бөлек жинау (пластик +15 EC, металл +10 EC, шыны +20 EC) пен геймификацияны біріктіреді. Жиналған EcoCoins тек мектеп асханасында (шырын 50 EC, тоқаш 40 EC, жеміс жинағы 60 EC, сэндвич 70 EC, эко-шоппер 450 EC) жұмсалады.
2. Қолдану жолы: жеке QR-кодты EcoBox сканеріне көрсет → ашылған тиісті бөлімге қалдық сал → EcoCoins пен операциялар тарихын бақыла → асханада QR арқылы алмастыр.
3. Сұрыптау және әділдік: материал қате таңдалса немесе контейнер қатені тіркесе, балл есептелмейді — жүйе оқушылар мен сыныптардың әділ рейтингін қалыптастырады.
4. Қарым-қатынас стилі: мейірімді, нақты жауап бер. Контейнерде техникалық ақау болса, мектеп әкімшісіне немесе техқолдауға жүгінуді ұсын.
Қазіргі аккаунт: Томирис (8 «А»), баланс ${balance} EcoCoins, деңгей «${levelName}», рейтинг #${rank}. Тек қазақ тілінде жауап бер.`;

      const recentHistory = Array.isArray(history)
        ? (history as HistoryTurn[])
            .slice(-6)
            .map((h) => `${h.sender === 'user' ? 'Пользователь' : 'Эко-гид'}: ${h.text}`)
            .join('\n')
        : '';

      const promptContents = recentHistory
        ? `${recentHistory}\nПользователь: ${cleanMessage}`
        : cleanMessage;

      const response = await ai.models.generateContent({
        model: 'gemini-3.8-flash',
        contents: promptContents,
        config: {
          systemInstruction: lang === 'kk' ? baseKkInstruction : baseRuInstruction,
          thinkingConfig: { thinkingLevel: ThinkingLevel.LOW },
        },
      });

      const replyText = response.text?.trim();
      if (replyText) {
        res.json({ reply: replyText, source: 'gemini' });
        return;
      }
    } catch (error) {
      console.warn('Gemini EcoBot fallback triggered:', error instanceof Error ? error.message : error);
    }

    res.json({
      reply: getLocalEcoBotReply(cleanMessage, lang, Number(balance) || 245),
      source: 'local',
    });
  });

  if (process.env.NODE_ENV !== 'production') {
    const { createServer: createViteServer } = await import('vite');
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    const distDir = path.resolve(__dirname, 'dist');
    app.use(express.static(distDir));
    app.get('*', (_req, res) => {
      res.sendFile(path.join(distDir, 'index.html'));
    });
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`EcoBox server running on http://0.0.0.0:${PORT}`);
  });
}

startServer();
